from __future__ import annotations

from pathlib import Path
import argparse
import json
import re


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "native" / "bpf_lsm" / "memguard_lsm_policy.h"
SAFE_PATTERN = re.compile(r"^/[A-Za-z0-9._@%+=:,/~-]{2,120}$")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate a static MemGuardOS BPF LSM denylist header from JSON")
    parser.add_argument("--policy", required=True, help="JSON file containing deny_substrings")
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--max-items", type=int, default=12)
    args = parser.parse_args()

    policy = json.loads(Path(args.policy).read_text(encoding="utf-8"))
    raw_items = policy.get("deny_substrings", [])
    if not isinstance(raw_items, list):
        raise SystemExit("policy.deny_substrings must be an array")
    items = []
    for raw in raw_items:
        item = str(raw).strip()
        if not SAFE_PATTERN.match(item):
            raise SystemExit("unsafe deny substring: %s" % item)
        if item not in items:
            items.append(item)
    if len(items) > args.max_items:
        raise SystemExit("too many deny substrings: %s > %s" % (len(items), args.max_items))

    output = Path(args.output)
    output.write_text(render_header(items, Path(args.policy).name), encoding="utf-8")
    print(json.dumps({"output": str(output), "deny_substrings": items}, ensure_ascii=False, indent=2))
    return 0


def render_header(items: list[str], policy_name: str) -> str:
    lines = [
        "// SPDX-License-Identifier: GPL-2.0",
        "// Generated by scripts/generate_bpf_lsm_policy.py from %s." % policy_name,
        "// Review before loading on any non-disposable machine.",
        "",
        "#ifndef MEMGUARD_LSM_POLICY_H",
        "#define MEMGUARD_LSM_POLICY_H",
        "",
        "static __always_inline int memguard_custom_sensitive_path(const char *path)",
        "{",
    ]
    if not items:
        lines.append("    (void)path;")
        lines.append("    return 0;")
    else:
        for item in items:
            lines.append('    if (contains(path, "%s"))' % _c_escape(item))
            lines.append("        return 1;")
        lines.append("    return 0;")
    lines.extend(["}", "", "#endif", ""])
    return "\n".join(lines)


def _c_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


if __name__ == "__main__":
    raise SystemExit(main())
