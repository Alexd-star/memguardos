from pathlib import Path
from typing import Dict, Optional
import json
import re

from memguard.store.permissions import ensure_private_directory, ensure_private_file


class PatternValidationError(ValueError):
    pass


_DEFAULT_PATTERN_NAMES = {
    "工号": "employee_id",
    "员工号": "employee_id",
    "员工编号": "employee_id",
    "客户编号": "customer_id",
    "客户号": "customer_id",
    "订单号": "order_id",
    "设备编号": "device_id",
    "项目代号": "project_code",
    "内部编号": "internal_id",
    "合同编号": "contract_id",
}


VALID_LEVELS = ("high", "medium", "low")


def load_patterns(path: Path) -> Dict[str, object]:
    """Load custom patterns, keeping both the legacy string form and the {regex, level} form."""

    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    patterns: Dict[str, object] = {}
    for key, value in data.items():
        if isinstance(value, dict):
            regex = str(value.get("regex", ""))
            level = str(value.get("level", "")).strip().lower()
            patterns[str(key)] = {"regex": regex, "level": level} if level in VALID_LEVELS else regex
        else:
            patterns[str(key)] = str(value)
    return patterns


def pattern_regex(spec: object) -> str:
    return str(spec.get("regex", "")) if isinstance(spec, dict) else str(spec)


def save_pattern(path: Path, name: str, regex: str, level: str = "") -> Dict[str, object]:
    validate_pattern(name, regex)
    normalized_level = str(level or "").strip().lower()
    if normalized_level and normalized_level not in VALID_LEVELS:
        raise PatternValidationError("pattern level must be one of: %s" % ", ".join(VALID_LEVELS))
    patterns = load_patterns(path)
    patterns[name] = {"regex": regex, "level": normalized_level} if normalized_level else regex
    ensure_private_directory(path.parent)
    path.write_text(json.dumps(patterns, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")
    ensure_private_file(path)
    return patterns


def suggest_pattern_from_instruction(instruction: str, name: Optional[str] = None) -> Dict[str, object]:
    """Build a conservative regex from a natural-language sensitive-pattern instruction.

    This helper intentionally supports a small, explainable subset instead of
    trying to be a general regex generator. The generated pattern still passes
    the same validation path as manually configured rules.
    """

    text = " ".join((instruction or "").strip().split())
    if not text:
        raise PatternValidationError("natural-language instruction must not be empty")

    inferred_name = name or _infer_pattern_name(text)
    regex = _extract_explicit_regex(text) or _prefix_count_pattern(text) or _sample_pattern(text)
    if not regex:
        raise PatternValidationError(
            "could not infer a safe sensitive pattern; use examples like '把工号，格式 MG- 后接 6 位数字，作为敏感信息'"
        )
    validate_pattern(inferred_name, regex)
    return {
        "name": inferred_name,
        "regex": regex,
        "instruction": text,
        "source": "natural_language",
        "notes": [
            "generated by a conservative rule parser",
            "validated before saving",
            "review the regex before using it in production",
        ],
    }


def save_pattern_from_instruction(path: Path, instruction: str, name: Optional[str] = None) -> Dict[str, object]:
    suggestion = suggest_pattern_from_instruction(instruction, name=name)
    patterns = save_pattern(path, str(suggestion["name"]), str(suggestion["regex"]))
    suggestion["patterns"] = patterns
    return suggestion


def validate_pattern(name: str, regex: str) -> None:
    if not re.fullmatch(r"[A-Za-z0-9_.-]{1,64}", name):
        raise PatternValidationError("pattern name must be 1-64 chars of letters, digits, dot, underscore or dash")
    if not regex or len(regex) > 512:
        raise PatternValidationError("pattern regex must be non-empty and at most 512 chars")
    try:
        compiled = re.compile(regex)
    except re.error as exc:
        raise PatternValidationError("invalid regex: %s" % exc) from exc
    if compiled.search(""):
        raise PatternValidationError("pattern must not match empty text")
    ordinary = "this is an ordinary linux memory sentence without secrets"
    match = compiled.search(ordinary)
    if match and len(match.group(0)) >= max(8, len(ordinary) // 2):
        raise PatternValidationError("pattern is too broad for a sensitive detector")


def _infer_pattern_name(text: str) -> str:
    for marker, name in _DEFAULT_PATTERN_NAMES.items():
        if marker in text:
            return name
    sample = _extract_sample_token(text)
    if sample:
        prefix = re.match(r"[A-Za-z]{2,16}", sample)
        if prefix:
            return prefix.group(0).lower() + "_code"
    return "custom_sensitive"


def _extract_explicit_regex(text: str) -> str:
    for pattern in (r"regex\s*[:=：]\s*`([^`]+)`", r"正则\s*[:=：]\s*`([^`]+)`", r"/([^/\n]{3,256})/"):
        match = re.search(pattern, text, flags=re.IGNORECASE)
        if match:
            return match.group(1).strip()
    return ""


def _prefix_count_pattern(text: str) -> str:
    prefix = _extract_prefix(text)
    count_match = re.search(r"(\d{1,2})\s*(?:位|个)?\s*(数字|数|字母数字|英文数字|大小写字母数字|字符)", text)
    if not prefix or not count_match:
        return ""
    count = int(count_match.group(1))
    kind = count_match.group(2)
    if count < 2 or count > 64:
        raise PatternValidationError("natural-language pattern length must be between 2 and 64")
    if kind in {"数字", "数"}:
        tail = r"\d{%d}" % count
    elif "字母数字" in kind or "英文数字" in kind:
        tail = r"[A-Za-z0-9]{%d}" % count
    else:
        tail = r"[A-Za-z0-9_-]{%d}" % count
    return r"(?<![A-Za-z0-9])%s%s(?![A-Za-z0-9])" % (re.escape(prefix), tail)


def _extract_prefix(text: str) -> str:
    patterns = [
        r"(?:以|用)\s*`?([A-Za-z][A-Za-z0-9_-]{1,24})`?\s*(?:开头|作为前缀)",
        r"(?:前缀|prefix)\s*(?:是|为|=|:|：)?\s*`?([A-Za-z][A-Za-z0-9_-]{1,24})`?",
        r"(?:格式|形如|例如|样例|示例)\s*(?:是|为|:|：)?\s*`?([A-Za-z][A-Za-z0-9_-]{1,40})`?",
    ]
    for pattern in patterns:
        match = re.search(pattern, text, flags=re.IGNORECASE)
        if match:
            token = match.group(1)
            digit_index = next((idx for idx, ch in enumerate(token) if ch.isdigit()), len(token))
            return token[:digit_index]
    return ""


def _sample_pattern(text: str) -> str:
    sample = _extract_sample_token(text)
    if not sample:
        return ""
    pieces = []
    idx = 0
    while idx < len(sample):
        char = sample[idx]
        end = idx + 1
        if char.isdigit():
            while end < len(sample) and sample[end].isdigit():
                end += 1
            pieces.append(r"\d{%d}" % (end - idx))
        elif "A" <= char <= "Z":
            while end < len(sample) and "A" <= sample[end] <= "Z":
                end += 1
            pieces.append(r"[A-Z]{%d}" % (end - idx))
        elif "a" <= char <= "z":
            while end < len(sample) and "a" <= sample[end] <= "z":
                end += 1
            pieces.append(r"[a-z]{%d}" % (end - idx))
        elif char in "-_.":
            while end < len(sample) and sample[end] == char:
                end += 1
            pieces.append(re.escape(sample[idx:end]))
        else:
            pieces.append(re.escape(char))
        idx = end
    return r"(?<![A-Za-z0-9])%s(?![A-Za-z0-9])" % "".join(pieces)


def _extract_sample_token(text: str) -> str:
    candidates = re.findall(r"[A-Za-z][A-Za-z0-9_.-]{3,64}", text)
    for candidate in candidates:
        if any(ch.isdigit() for ch in candidate) and any(ch.isalpha() for ch in candidate):
            return candidate.rstrip("。；;,，")
    return ""
