from __future__ import annotations

from argparse import ArgumentParser
from pathlib import Path
from typing import Any
import json


DEFAULT_THRESHOLDS = {
    "same_workload": True,
    "success_rate_min": 1.0,
    "latency_p95_ms_max": 500.0,
    "latency_p99_ms_max": 2000.0,
    "peak_rss_mb_max": 512.0,
    "mean_cpu_percent_max": 80.0,
}


def evaluate_slo(report: dict[str, Any], thresholds: dict[str, float | bool] | None = None) -> dict[str, Any]:
    thresholds = {**DEFAULT_THRESHOLDS, **(thresholds or {})}
    enabled = (report.get("results") or {}).get("memguardos_enabled") or {}
    latency = enabled.get("latency") or {}
    resources = enabled.get("resources") or {}
    protocol = report.get("protocol") or {}
    checks = [
        _check_equal("same_workload", bool(protocol.get("same_workload")), bool(thresholds["same_workload"])),
        _check_min("success_rate", float(enabled.get("success_rate", 0.0)), float(thresholds["success_rate_min"])),
        _check_max("latency.p95_ms", float(latency.get("p95_ms", float("inf"))), float(thresholds["latency_p95_ms_max"])),
        _check_max("latency.p99_ms", float(latency.get("p99_ms", float("inf"))), float(thresholds["latency_p99_ms_max"])),
        _check_max("resources.peak_rss_mb", float(resources.get("peak_rss_mb", float("inf"))), float(thresholds["peak_rss_mb_max"])),
        _check_max("resources.mean_cpu_percent", float(resources.get("mean_cpu_percent", float("inf"))), float(thresholds["mean_cpu_percent_max"])),
    ]
    failed = [check for check in checks if not check["ok"]]
    return {
        "ok": not failed,
        "thresholds": thresholds,
        "checks": checks,
        "failed": [
            {key: value for key, value in check.items() if key != "ok"}
            for check in failed
        ],
    }


def _check_equal(metric: str, actual: bool, expected: bool) -> dict[str, object]:
    return {"ok": actual == expected, "metric": metric, "actual": actual, "threshold": expected}


def _check_min(metric: str, actual: float, threshold: float) -> dict[str, object]:
    return {"ok": actual >= threshold, "metric": metric, "actual": actual, "threshold": threshold}


def _check_max(metric: str, actual: float, threshold: float) -> dict[str, object]:
    return {"ok": actual <= threshold, "metric": metric, "actual": actual, "threshold": threshold}


def main() -> int:
    parser = ArgumentParser(description="Check MemGuardOS resource and latency SLO gates.")
    parser.add_argument("report", type=Path, help="JSON report generated by scripts/run_resource_control.py")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--p95-ms", type=float, default=DEFAULT_THRESHOLDS["latency_p95_ms_max"])
    parser.add_argument("--p99-ms", type=float, default=DEFAULT_THRESHOLDS["latency_p99_ms_max"])
    parser.add_argument("--peak-rss-mb", type=float, default=DEFAULT_THRESHOLDS["peak_rss_mb_max"])
    parser.add_argument("--mean-cpu-percent", type=float, default=DEFAULT_THRESHOLDS["mean_cpu_percent_max"])
    args = parser.parse_args()
    report = json.loads(args.report.read_text(encoding="utf-8"))
    result = evaluate_slo(
        report,
        {
            "latency_p95_ms_max": args.p95_ms,
            "latency_p99_ms_max": args.p99_ms,
            "peak_rss_mb_max": args.peak_rss_mb,
            "mean_cpu_percent_max": args.mean_cpu_percent,
        },
    )
    raw = json.dumps(result, ensure_ascii=False, indent=2)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(raw, encoding="utf-8")
    print(raw)
    return 0 if result["ok"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
